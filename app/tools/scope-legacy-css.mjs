/* Builds src/styles/legacy-scoped.css: the prototype's app.css + polish.css with
   every rule nested under `.hb-legacy`, so the unchanged report renderer
   (src/legacy/hb-report.js) looks exactly as before inside an Angular page,
   without the prototype's generic class names (.btn, .card, .row ...) leaking
   into the Bootstrap pages. Run:  node tools/scope-legacy-css.mjs  */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const postcss = require('postcss');

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const files = ['../css/app.css', '../css/polish.css'].map(f => path.join(root, f));
const S = '.hb-legacy';

function scope(sel) {
  sel = sel.trim();
  if (/^(html|body)$/.test(sel)) return S;
  if (/^(html|body)\s+/.test(sel)) return sel.replace(/^(html|body)\s+/, S + ' ');
  if (sel.startsWith(':root')) return null;
  if (/::-webkit-scrollbar/.test(sel)) return null;
  if (/^main\b/.test(sel)) return null;
  if (/^#toast\b|^\.toast\b|^\.demo-strip\b/.test(sel)) return null;
  return S + ' ' + sel;
}

let out = '/* GENERATED by tools/scope-legacy-css.mjs from the prototype css — do not edit by hand */\n';
for (const f of files) {
  const ast = postcss.parse(fs.readFileSync(f, 'utf8'), { from: f });
  ast.walkAtRules('import', r => r.remove());
  ast.walkRules(rule => {
    if (rule.parent && rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    const sels = rule.selectors.map(scope).filter(Boolean);
    if (!sels.length) { rule.remove(); return; }
    rule.selectors = sels;
  });
  ast.walkAtRules(/keyframes/, r => r.remove());   /* the global stylesheet already has them */
  out += ast.toString() + '\n';
}

/* Bootstrap defines .row / .card / .btn / .badge too: undo its parts inside the report */
out += `
/* ---- Bootstrap resets inside the legacy report ---- */
${S} .row{--bs-gutter-x:0;--bs-gutter-y:0;margin:0;flex-wrap:nowrap}
${S} .row-b{margin:0}
${S} .row>*{flex-shrink:1;width:auto;max-width:none;padding-left:0;padding-right:0;margin-top:0}
${S} .card{display:block;--bs-card-spacer-y:0;--bs-card-spacer-x:0}
${S} .btn{--bs-btn-bg:var(--brand);--bs-btn-color:#fff;--bs-btn-border-color:transparent;--bs-btn-hover-bg:var(--brand-dk);--bs-btn-hover-color:#fff;--bs-btn-active-bg:var(--brand-dk);--bs-btn-active-color:#fff;--bs-btn-active-border-color:transparent;line-height:1.5}
${S} .btn-ghost{--bs-btn-bg:#fff;--bs-btn-color:var(--ink);--bs-btn-border-color:var(--line);--bs-btn-hover-bg:#fff;--bs-btn-hover-color:var(--brand);--bs-btn-active-bg:#fff;--bs-btn-active-color:var(--brand)}
${S} .btn-soft{--bs-btn-bg:rgba(var(--brand-rgb),.09);--bs-btn-color:var(--brand);--bs-btn-hover-bg:rgba(var(--brand-rgb),.16);--bs-btn-hover-color:var(--brand-dk);--bs-btn-active-bg:rgba(var(--brand-rgb),.16);--bs-btn-active-color:var(--brand-dk)}
${S} .btn-line{--bs-btn-bg:rgba(255,255,255,.07);--bs-btn-color:#fff;--bs-btn-border-color:rgba(255,255,255,.32);--bs-btn-hover-bg:rgba(255,255,255,.16);--bs-btn-hover-color:#fff;--bs-btn-active-bg:rgba(255,255,255,.16);--bs-btn-active-color:#fff}
${S} .badge{line-height:1.35}
${S} .alert{margin-bottom:0}
${S}{background:transparent!important}
${S} p{margin-bottom:0}
${S} ul,${S} ol{margin-bottom:0}
`;
fs.writeFileSync(path.join(root, 'src/styles/legacy-scoped.css'), out);
console.log('wrote src/styles/legacy-scoped.css', out.length, 'bytes');
